/**
 * The app's icons, as vectors generated from the upstream Material Icons "outlined" set.
 *
 * These exist instead of the `material-icons-extended` dependency, which is a **37 MB** jar holding
 * every Material glyph because each one is a compiled Kotlin object. This app draws 13. Carrying the
 * whole set to get 0.65% of it was the largest avoidable cost in the Windows install.
 *
 * Geometry is copied verbatim from `google/material-design-icons`
 * (`src/<category>/<name>/materialiconsoutlined/24px.svg`, Apache-2.0), so the glyphs render exactly
 * the way the Material set draws them -- same 24x24 grid, same path commands, nothing redrawn by hand.
 * The transparent bounding rectangle each SVG carries is dropped: it sizes the canvas, and filling it
 * would paint a solid 24x24 square over the icon.
 *
 * `addPathNodes` is the same SVG path parse JetBrains' own icon generator performs, so a glyph here and the equivalent `Icons.Outlined` glyph produce identical geometry --
 * which is what makes this a drop-in replacement rather than a redraw. Adding an icon means pasting
 * its `d` attribute below; there is no dependency and nothing to download.
 *
 * Fill is declared as black and retinted per call site by `Icon(tint = ...)`, the same contract the
 * generated libraries follow.
 */
private fun materialIcon(
    name: String,
    builder: ImageVector.Builder.() -> Unit,
): ImageVector = ImageVector.Builder(
    name = name,
    defaultWidth = 24.dp,
    defaultHeight = 24.dp,
    viewportWidth = 24f,
    viewportHeight = 24f,
).apply(builder).build()

